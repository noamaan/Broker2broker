-- Complimentary access is a subscription, not a payment. Existing payment rows are unchanged.
alter table public.subscriptions alter column payment_request_id drop not null;
alter table public.subscriptions alter column payment_id drop not null;
alter table public.subscriptions add column source text not null default 'PAYMENT';
alter table public.subscriptions add column grant_reason text;
alter table public.subscriptions add constraint subscriptions_source_consistency check (
  (source='PAYMENT' and payment_request_id is not null and payment_id is not null and grant_reason is null)
  or (source='COMPLIMENTARY' and payment_request_id is null and payment_id is null and amount=0 and length(trim(coalesce(grant_reason,''))) between 5 and 500)
);

-- The UUID is an idempotency key generated by the client for a single confirmed action.
-- The target row lock serializes grants with payment approvals and other grants.
create or replace function public.b2b_grant_complimentary_membership(
  p_actor_id text, p_user_id text, p_plan text, p_reason text, p_grant_id uuid
) returns jsonb language plpgsql security definer set search_path=public as $$
declare
  v_actor public.users%rowtype; v_user public.users%rowtype; v_existing public.subscriptions%rowtype;
  v_subscription_id text := 'GFT-' || p_grant_id::text;
  v_days integer; v_now timestamptz := now(); v_start timestamptz; v_expires timestamptz; v_renewal boolean;
begin
  select * into v_actor from public.users where user_id=p_actor_id and role='DEVELOPER' and account_status='ACTIVE';
  if not found or not exists(select 1 from public.platform_config where key='developer_user_id' and value=p_actor_id)
    or not exists(select 1 from public.developers where user_id=p_actor_id and status='ACTIVE') then
    raise exception using errcode='P0001', message='FORBIDDEN: Only the original active developer can grant complimentary access.';
  end if;
  if p_grant_id is null or p_plan not in ('MONTHLY','YEARLY') or p_plan is null
    or length(trim(coalesce(p_reason,''))) not between 5 and 500 then
    raise exception using errcode='P0001', message='INVALID_INPUT: Select a plan and enter a reason of 5 to 500 characters.';
  end if;
  select * into v_user from public.users where user_id=p_user_id for update;
  if not found then raise exception using errcode='P0001', message='NOT_FOUND: Account not found.'; end if;
  select * into v_existing from public.subscriptions where subscription_id=v_subscription_id;
  if found then
    if v_existing.source<>'COMPLIMENTARY' or v_existing.user_id<>p_user_id or v_existing.approved_by<>p_actor_id
      or v_existing.plan<>p_plan or v_existing.grant_reason<>trim(p_reason) then
      raise exception using errcode='P0001', message='CONFLICT: This grant reference was already used for a different action.';
    end if;
    return jsonb_build_object('subscription_id',v_subscription_id,'starts_at',v_existing.starts_at,'expires_at',v_existing.expires_at,'replayed',true);
  end if;
  if v_user.account_status<>'ACTIVE' or v_user.role not in ('USER','ADMIN') or p_user_id=p_actor_id then
    raise exception using errcode='P0001', message='FORBIDDEN: Complimentary access can only be granted to an active member or administrator.';
  end if;
  if p_plan='MONTHLY' then v_days:=30;
  else
    select coalesce(nullif(value,''),'365')::integer into v_days from public.settings where key='payment.yearlyDurationDays';
    v_days:=coalesce(v_days,365);
    if v_days<1 or v_days>730 then raise exception using errcode='P0001', message='INVALID_INPUT: Invalid yearly plan duration in settings.'; end if;
  end if;
  v_renewal:=v_user.membership_status='ACTIVE' and v_user.membership_expires_at is not null and v_user.membership_expires_at>v_now;
  v_start:=case when v_renewal then v_user.membership_expires_at else v_now end;
  v_expires:=v_start+make_interval(days=>v_days);
  update public.subscriptions set status='RENEWED' where user_id=p_user_id and status='ACTIVE' and expires_at>v_now;
  insert into public.subscriptions(subscription_id,user_id,payment_request_id,payment_id,plan,amount,duration_days,status,starts_at,expires_at,approved_by,renewal_type,source,grant_reason,created_at)
  values(v_subscription_id,p_user_id,null,null,p_plan,0,v_days,'ACTIVE',v_start,v_expires,p_actor_id,case when v_renewal then 'RENEWAL' else 'NEW' end,'COMPLIMENTARY',trim(p_reason),v_now);
  update public.users set membership_status='ACTIVE',current_plan=p_plan,membership_start_at=v_start,membership_expires_at=v_expires,updated_at=v_now where user_id=p_user_id;
  insert into public.notifications(notification_id,user_id,type,title,body,related_id,created_at)
  values('NTF-'||upper(replace(gen_random_uuid()::text,'-','')),p_user_id,'MEMBERSHIP_GRANTED','Complimentary membership granted',
    'A complimentary '||lower(p_plan)||' membership has been granted. Your access is valid until '||to_char(v_expires at time zone 'Asia/Kolkata','DD Mon YYYY')||'.',v_subscription_id,v_now);
  insert into public.audit_logs(audit_id,actor_id,action,entity_type,entity_id,details,created_at)
  values('AUD-'||upper(replace(gen_random_uuid()::text,'-','')),p_actor_id,'COMPLIMENTARY_MEMBERSHIP_GRANTED','USER',p_user_id,
    jsonb_build_object('subscriptionID',v_subscription_id,'plan',p_plan,'durationDays',v_days,'startsAt',v_start,'expiresAt',v_expires,'reason',trim(p_reason)),v_now);
  return jsonb_build_object('subscription_id',v_subscription_id,'starts_at',v_start,'expires_at',v_expires,'replayed',false);
end;
$$;
revoke all on function public.b2b_grant_complimentary_membership(text,text,text,text,uuid) from public, anon, authenticated;
grant execute on function public.b2b_grant_complimentary_membership(text,text,text,text,uuid) to service_role;
